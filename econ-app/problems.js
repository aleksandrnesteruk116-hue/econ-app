      idea: 'Предельные издержки — цена «ещё одной единицы» выпуска.',
      solution: `TC = FC + VC = ${fc} + ${vcs[q]} = ${tc}\nAC = TC / Q = ${tc} / ${q} = ${f(tc / q)}\nMC = ΔTC / ΔQ = ${vcs[q]} − ${vcs[q - 1]} = ${mc} (на 1 ед. выпуска)`,
      search: 'издержки производства общие средние предельные',
